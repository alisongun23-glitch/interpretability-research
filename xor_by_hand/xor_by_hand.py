"""XOR on a 2 -> 2 -> 1 sigmoid network, computed step by step.

    python xor_by_hand/xor_by_hand.py      # writes XOR_BY_HAND.md and history.npz next to this file

Network:  h_j = sigmoid(w1j*x1 + w2j*x2 + b_j)   for j = 1, 2   (hidden)
          p   = sigmoid(v1*h1 + v2*h2 + c)                       (output)
Loss:     mean over the 4 inputs of  -[y log p + (1-y) log(1-p)]  (binary cross-entropy)
Training: full-batch gradient descent, learning rate 1, starting from seed 3 (weights rounded to
          2 decimals so the first step can be followed with a calculator).
"""
import os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
X = np.array([[0, 0], [0, 1], [1, 0], [1, 1]], float)
Y = np.array([0, 1, 1, 0], float)
SEED, LR, MAX_STEPS = 3, 1.0, 5000
sig = lambda z: 1 / (1 + np.exp(-z))


def init():
    r = np.random.default_rng(SEED)
    W = np.round(r.normal(0, 1, (2, 2)), 2)      # W[i, j]: input i -> hidden j
    b = np.round(r.normal(0, 1, 2), 2)
    v = np.round(r.normal(0, 1, 2), 2)
    return {"W": W, "b": b, "v": v, "c": 0.0}


def forward(P):
    Z = X @ P["W"] + P["b"]; H = sig(Z)
    zo = H @ P["v"] + P["c"]; p = sig(zo)
    loss = float(np.mean(-(Y * np.log(p) + (1 - Y) * np.log(1 - p))))
    return Z, H, zo, p, loss


def grads(P):
    Z, H, zo, p, loss = forward(P)
    d_o = (p - Y) / 4                         # dLoss/dzo for each input (sigmoid + cross-entropy)
    g = {"v": H.T @ d_o, "c": d_o.sum()}
    d_h = np.outer(d_o, P["v"]) * H * (1 - H)  # dLoss/dz_hidden
    g["W"] = X.T @ d_h; g["b"] = d_h.sum(0)
    return g, (Z, H, zo, p, loss, d_o, d_h)


def train():
    P = init(); hist = []
    for t in range(MAX_STEPS + 1):
        g, (Z, H, zo, p, loss, *_ ) = grads(P)
        hist.append({"W": P["W"].copy(), "b": P["b"].copy(), "v": P["v"].copy(), "c": P["c"], "p": p, "H": H, "loss": loss})
        if np.all(np.abs(p - Y) < 0.1):
            break
        for k in P:
            P[k] = P[k] - LR * g[k]
    return hist


n = lambda x: f"{x:.4f}" if x >= 0 else f"({x:.4f})"


def lin(terms, bias, d=2):
    """'a·x + b·y − c' with proper signs. terms: list of (coef, value_text)."""
    out = ""
    for i, (w, x) in enumerate(terms + [(bias, None)]):
        mag = f"{abs(w):.{d}f}" + (f"·{x}" if x is not None else "")
        out += (("−" if w < 0 else "") if i == 0 else (" − " if w < 0 else " + ")) + mag
    return out


def write_md(hist):
    P0 = {k: (v.copy() if hasattr(v, "copy") else v) for k, v in hist[0].items() if k in ("W", "b", "v", "c")}
    g, (Z, H, zo, p, loss, d_o, d_h) = grads(P0)
    W, b, v, c = P0["W"], P0["b"], P0["v"], P0["c"]
    L = ["# XOR by hand: a 2 → 2 → 1 network learns XOR", "",
         "Generated by `xor_by_hand.py`; every number below is the program's arithmetic, written out.", "",
         "## The network", "",
         "Two inputs x₁, x₂; two hidden sigmoid neurons; one sigmoid output. σ(z) = 1 / (1 + e^(−z)).", "",
         "    h₁ = σ(w₁₁·x₁ + w₂₁·x₂ + b₁)",
         "    h₂ = σ(w₁₂·x₁ + w₂₂·x₂ + b₂)",
         "    p  = σ(v₁·h₁ + v₂·h₂ + c)", "",
         "Loss = average over the 4 inputs of −[y·log p + (1−y)·log(1−p)].", "",
         f"## Step 0: random start (seed {SEED}, rounded to 2 decimals)", "",
         "| weight | value | | weight | value |", "|---|---|---|---|---|",
         f"| w₁₁ (x₁→h₁) | {W[0,0]:.2f} | | w₁₂ (x₁→h₂) | {W[0,1]:.2f} |",
         f"| w₂₁ (x₂→h₁) | {W[1,0]:.2f} | | w₂₂ (x₂→h₂) | {W[1,1]:.2f} |",
         f"| b₁ | {b[0]:.2f} | | b₂ | {b[1]:.2f} |",
         f"| v₁ (h₁→out) | {v[0]:.2f} | | v₂ (h₂→out) | {v[1]:.2f} |",
         f"| c | {c:.2f} | | | |", "",
         "### Forward pass, all four inputs", ""]
    for i, (x1, x2) in enumerate(X):
        L += [f"**Input ({int(x1)}, {int(x2)}), target {int(Y[i])}**", "",
              f"    z₁ = {lin([(W[0,0], int(x1)), (W[1,0], int(x2))], b[0])} = {Z[i,0]:.4f}    h₁ = σ({Z[i,0]:.4f}) = {H[i,0]:.4f}",
              f"    z₂ = {lin([(W[0,1], int(x1)), (W[1,1], int(x2))], b[1])} = {Z[i,1]:.4f}    h₂ = σ({Z[i,1]:.4f}) = {H[i,1]:.4f}",
              f"    zₒ = {lin([(v[0], f'{H[i,0]:.4f}'), (v[1], f'{H[i,1]:.4f}')], c)} = {zo[i]:.4f}    p = σ({zo[i]:.4f}) = {p[i]:.4f}",
              f"    loss term = −log({'p' if Y[i] else '1 − p'}) = −log({(p[i] if Y[i] else 1 - p[i]):.4f}) = {-np.log(p[i] if Y[i] else 1 - p[i]):.4f}", ""]
    L += [f"Average loss = {loss:.4f}. The network says {', '.join(f'{x:.2f}' for x in p)} for targets 0, 1, 1, 0: "
          "roughly the same answer for every input, so it has learned nothing yet.", "",
          "### Backward pass", "",
          "For a sigmoid output with cross-entropy, the error signal at the output is simply "
          "δₒ = (p − y) / 4 (the 4 averages over inputs).", "",
          "| input | p − y | δₒ | δ₁ = δₒ·v₁·h₁(1−h₁) | δ₂ = δₒ·v₂·h₂(1−h₂) |", "|---|---|---|---|---|"]
    for i, (x1, x2) in enumerate(X):
        L.append(f"| ({int(x1)}, {int(x2)}) | {p[i]-Y[i]:.4f} | {d_o[i]:.4f} | {d_o[i]:.4f}·{v[0]:.2f}·{H[i,0]*(1-H[i,0]):.4f} = {d_h[i,0]:.5f} | "
                 f"{d_o[i]:.4f}·{v[1]:.2f}·{H[i,1]*(1-H[i,1]):.4f} = {d_h[i,1]:.5f} |")
    L += ["", "Each gradient is a sum over the 4 inputs of (error signal) × (what fed that weight):", "",
          f"    ∂L/∂v₁ = Σ δₒ·h₁ = " + " + ".join(f"{n(d_o[i])}·{H[i,0]:.4f}" for i in range(4)) + f" = {g['v'][0]:.4f}",
          f"    ∂L/∂v₂ = Σ δₒ·h₂ = " + " + ".join(f"{n(d_o[i])}·{H[i,1]:.4f}" for i in range(4)) + f" = {g['v'][1]:.4f}",
          f"    ∂L/∂c  = Σ δₒ = {g['c']:.4f}",
          f"    ∂L/∂w₁₁ = Σ δ₁·x₁ = {g['W'][0,0]:.5f}     ∂L/∂w₂₁ = Σ δ₁·x₂ = {g['W'][1,0]:.5f}     ∂L/∂b₁ = Σ δ₁ = {g['b'][0]:.5f}",
          f"    ∂L/∂w₁₂ = Σ δ₂·x₁ = {g['W'][0,1]:.5f}     ∂L/∂w₂₂ = Σ δ₂·x₂ = {g['W'][1,1]:.5f}     ∂L/∂b₂ = Σ δ₂ = {g['b'][1]:.5f}", "",
          f"### Update (learning rate {LR:g}): new = old − {LR:g} × gradient", "",
          "| weight | old | gradient | new |", "|---|---|---|---|"]
    rows = [("w₁₁", W[0,0], g["W"][0,0]), ("w₂₁", W[1,0], g["W"][1,0]), ("b₁", b[0], g["b"][0]),
            ("w₁₂", W[0,1], g["W"][0,1]), ("w₂₂", W[1,1], g["W"][1,1]), ("b₂", b[1], g["b"][1]),
            ("v₁", v[0], g["v"][0]), ("v₂", v[1], g["v"][1]), ("c", c, g["c"])]
    for nm, o, gr in rows:
        L.append(f"| {nm} | {o:.4f} | {gr:.5f} | {o - LR*gr:.4f} |")
    L += ["", f"After this one step the loss is {hist[1]['loss']:.4f} (it was {hist[0]['loss']:.4f}). "
          "The rest of training repeats exactly these three moves (forward, backward, update).", "",
          "## Snapshots during training", "",
          "| step | loss | p(0,0) | p(0,1) | p(1,0) | p(1,1) |", "|---|---|---|---|---|---|"]
    T = len(hist) - 1
    for t in sorted(set([0, 1, 10, 50, 100, 150, 200, 250, 300, T])):
        if t <= T:
            h = hist[t]; L.append(f"| {t} | {h['loss']:.4f} | " + " | ".join(f"{x:.3f}" for x in h["p"]) + " |")
    F = hist[-1]; W, b, v, c = F["W"], F["b"], F["v"], F["c"]
    L += ["", f"## The trained network (step {T}: every output within 0.1 of its target)", "",
          f"    h₁ = σ({lin([(W[0,0], 'x₁'), (W[1,0], 'x₂')], b[0])})",
          f"    h₂ = σ({lin([(W[0,1], 'x₁'), (W[1,1], 'x₂')], b[1])})",
          f"    p  = σ({lin([(v[0], 'h₁'), (v[1], 'h₂')], c)})", "",
          "| x₁ x₂ | h₁ | h₂ | p | target |", "|---|---|---|---|---|"]
    for i, (x1, x2) in enumerate(X):
        L.append(f"| {int(x1)} {int(x2)} | {F['H'][i,0]:.3f} | {F['H'][i,1]:.3f} | {F['p'][i]:.3f} | {int(Y[i])} |")
    L += ["", "Read the columns as logic: h₁ is on only for (1, 1), so **h₁ = AND(x₁, x₂)**. "
          "h₂ is on only for (0, 0), so **h₂ = NOR(x₁, x₂)**. The output is on only when both hidden neurons "
          "are off, so **p = NOR(h₁, h₂)**. Together: XOR = NOR(AND, NOR), \"one or the other, but not both and not neither\".", "",
          "Why two hidden neurons are needed: one sigmoid neuron draws one straight line through the input square, "
          "and no single line separates (0,1), (1,0) from (0,0), (1,1). The hidden layer bends the space so that, in "
          "(h₁, h₂) coordinates, the two XOR-true points sit together near (0, 0) and the output neuron's one line "
          "can cut them off. The animations show this happening.", "",
          "Not every start works: with the same recipe, seeds 2, 6 and 8 get stuck for 20,000 steps with one or two "
          "outputs at 0.5 (a local minimum where a hidden neuron saturates and stops learning)."]
    open(os.path.join(HERE, "XOR_BY_HAND.md"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    hist = train()
    write_md(hist)
    np.savez(os.path.join(HERE, "history.npz"),
             **{k: np.array([h[k] for h in hist]) for k in ("W", "b", "v", "c", "p", "H", "loss")})
    print(f"trained in {len(hist) - 1} steps; final p = {np.round(hist[-1]['p'], 3)}")
